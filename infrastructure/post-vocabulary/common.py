"""Small, source-bound vocabulary jobs. No post text is kept in job records."""
import hashlib
import json
import logging
import os
import time
import uuid

import boto3
from boto3.dynamodb.conditions import Attr
from botocore.config import Config

from post_glossary import GLOSSARY_VERSION, saved_glossary, source_hash

LOG = logging.getLogger(__name__)
LOG.setLevel(logging.INFO)
SDK_CONFIG = Config(connect_timeout=2, read_timeout=3,
                    retries={"total_max_attempts": 2, "mode": "standard"})
DYNAMODB = boto3.resource("dynamodb", config=SDK_CONFIG)
POSTS = DYNAMODB.Table(os.environ.get("POSTS_TABLE", "TextReels"))
STATE = DYNAMODB.Table(os.environ.get("STATE_TABLE", "SmartyExplanations"))
MAX_ATTEMPTS = 3
MAX_ENQUEUES_PER_HOUR = 10
ENQUEUE_LEASE_SECONDS = 45
WORKER_LEASE_SECONDS = 150
QUEUE_RETENTION_SECONDS = 604800
HIDDEN_STATES = {"pending", "pending_review", "removed", "rejected", "hidden"}
OWNER_FIELDS = ("userId", "creatorId", "authorId", "ownerId")
SOURCE_FIELDS = ("title", "body", *OWNER_FIELDS, "visibility", "moderationStatus", "deleted", "isDeleted", "isAutoGenerated", "contentFingerprint", "subTopic")


class Busy(RuntimeError):
    pass


class RateLimited(RuntimeError):
    pass


def now():
    return int(time.time())


def digest(value):
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def valid_id(value):
    return isinstance(value, str) and 1 <= len(value) <= 200 and value == value.strip() and not any(ord(char) < 32 for char in value)


def visible(post):
    return bool(isinstance(post, dict) and post.get("deleted") is not True and post.get("isDeleted") is not True
                and str(post.get("moderationStatus") or "").strip().lower() not in HIDDEN_STATES
                and not str(post.get("visibility") or "").strip().lower().startswith("moderation_")
                and str(post.get("visibility") or "").strip().lower() not in {"hidden", "deleted", "removed"})


def owned(post, user_id):
    identities = {post[key] for key in OWNER_FIELDS if isinstance(post.get(key), str) and post[key].strip()}
    return identities == {user_id}


def generated(post):
    return (post.get("isAutoGenerated") is True or post.get("authorId") == "smarty-ai"
            or bool(post.get("contentFingerprint") and post.get("subTopic")))


def bounded_source(post):
    return (isinstance(post.get("title", ""), str) and isinstance(post.get("body", ""), str)
            and len(post.get("title", "")) <= 500 and len(post.get("body", "")) <= 12000
            and bool(post.get("title", "").strip() or post.get("body", "").strip()))


def read_post(post_id):
    return POSTS.get_item(Key={"id": post_id}, ConsistentRead=True).get("Item")


def key_for(post_id, fingerprint):
    return "post-vocabulary#v" + str(GLOSSARY_VERSION) + "#" + digest(post_id + "\n" + fingerprint)


def read_job(key):
    return STATE.get_item(Key={"explanationId": key}, ConsistentRead=True).get("Item")


def replace_job(previous, changes, key=None):
    """Compare-and-swap: a late producer or delivery cannot overwrite a worker."""
    item = {**(previous or {}), **changes, "revision": uuid.uuid4().hex}
    item["explanationId"] = (previous or {}).get("explanationId") or key
    condition = Attr("revision").eq(previous["revision"]) if previous else Attr("explanationId").not_exists()
    try:
        STATE.put_item(Item=item, ConditionExpression=condition)
    except STATE.meta.client.exceptions.ConditionalCheckFailedException as error:
        raise Busy() from error
    return item


def reserve_author_budget(user_id, timestamp):
    key = "post-vocabulary-budget#" + digest(user_id) + "#" + str(timestamp // 3600)
    for _ in range(3):
        prior = read_job(key)
        count = int((prior or {}).get("requestCount", 0))
        if count >= MAX_ENQUEUES_PER_HOUR:
            raise RateLimited()
        try:
            replace_job(prior, {"requestCount": count + 1, "expiresAt": (timestamp // 3600 + 1) * 3600 + 86400}, key)
            return
        except Busy:
            continue
    raise RateLimited()


def active_job(job, timestamp):
    if not job:
        return False
    state = job.get("status")
    if state in {"processing", "enqueuing"}:
        return int(job.get("leaseUntil", 0)) > timestamp
    return state == "queued" and int(job.get("queuedAt", 0)) + QUEUE_RETENTION_SECONDS > timestamp


def source_condition(post):
    condition = Attr("id").exists()
    for field in SOURCE_FIELDS:
        condition &= Attr(field).eq(post[field]) if field in post else Attr(field).not_exists()
    return condition


def persist_glossary(post, glossary):
    POSTS.update_item(Key={"id": post["id"]}, ConditionExpression=source_condition(post),
                      UpdateExpression="SET postGlossary = :glossary",
                      ExpressionAttributeValues={":glossary": glossary})


def safe_failure_code(error):
    # Provider messages and request bodies can contain private source material.
    return type(error).__name__


def response(status, payload, retry_after=None):
    headers = {"Content-Type": "application/json", "Cache-Control": "private, no-store",
               "Access-Control-Allow-Origin": os.environ.get("ALLOWED_ORIGIN", "https://smarty.wiki"),
               "Access-Control-Allow-Headers": "Content-Type,Authorization",
               "Access-Control-Allow-Methods": "OPTIONS,GET,POST"}
    if retry_after is not None:
        headers["Retry-After"] = str(retry_after)
    return {"statusCode": status, "headers": headers, "body": json.dumps(payload, ensure_ascii=False)}
