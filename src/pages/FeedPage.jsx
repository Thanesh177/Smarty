function getTopicCanvasPosition(index) {
  const cardsPerCluster = 12;

  

  const clusterCards = [
    { x: 16, y: 26, width: 210, height: 150 },
    { x: 254, y: 26, width: 180, height: 190 },
    { x: 462, y: 26, width: 228, height: 150 },

    { x: 16, y: 244, width: 184, height: 188 },
    { x: 228, y: 244, width: 244, height: 150 },
    { x: 500, y: 244, width: 190, height: 190 },

    { x: 16, y: 462, width: 226, height: 152 },
    { x: 270, y: 462, width: 182, height: 190 },
    { x: 480, y: 462, width: 218, height: 150 },

    { x: 16, y: 680, width: 188, height: 180 },
    { x: 232, y: 680, width: 232, height: 148 },
    { x: 492, y: 680, width: 176, height: 184 },
  ];

const clusterIndex = Math.floor(
  index / cardsPerCluster
);

const cardIndex = index % cardsPerCluster;
const cluster = getSpiralClusterPosition(clusterIndex);
const card = clusterCards[cardIndex];

const isDesktop =
  typeof window !== 'undefined' &&
  window.innerWidth >= 1024;

const clusterWidth = isDesktop ? 860 : 740;
const clusterHeight = isDesktop ? 1080 : 920;

const canvasCenterX = 1050;
const canvasCenterY = 720;

return {
  width: card.width,
  height: card.height,
  x:
    canvasCenterX +
    cluster.x * clusterWidth +
    card.x,
  y:
    canvasCenterY +
    cluster.y * clusterHeight +
    card.y,
};
}

function getSpiralClusterPosition(index) {
  if (index === 0) {
    return { x: 0, y: 0 };
  }

  const spiral = [
    { x: 1, y: 0 },
    { x: 1, y: 1 },
    { x: 0, y: 1 },
    { x: -1, y: 1 },
    { x: -1, y: 0 },
    { x: -1, y: -1 },
    { x: 0, y: -1 },
    { x: 1, y: -1 },

    { x: 2, y: -1 },
    { x: 2, y: 0 },
    { x: 2, y: 1 },
    { x: 2, y: 2 },
    { x: 1, y: 2 },
    { x: 0, y: 2 },
    { x: -1, y: 2 },
    { x: -2, y: 2 },
    { x: -2, y: 1 },
    { x: -2, y: 0 },
    { x: -2, y: -1 },
    { x: -2, y: -2 },
    { x: -1, y: -2 },
    { x: 0, y: -2 },
    { x: 1, y: -2 },
    { x: 2, y: -2 },
  ];

  return (
    spiral[index - 1] || {
      x: index % 5,
      y: Math.floor(index / 5),
    }
  );
}



function getTopicCanvasLayout(topicCount) {
  const edgePadding = 20;

  const cards = Array.from(
    { length: topicCount },
    (_, index) => ({
      index,
      ...getTopicCanvasPosition(index),
    })
  );

  if (cards.length === 0) {
    return {
      width: 800,
      height: 700,
      offsetX: 0,
      offsetY: 0,
    };
  }

  const minX = Math.min(
    ...cards.map((card) => card.x)
  );

  const minY = Math.min(
    ...cards.map((card) => card.y)
  );

  const maxX = Math.max(
    ...cards.map(
      (card) => card.x + card.width
    )
  );

  const maxY = Math.max(
    ...cards.map(
      (card) => card.y + card.height
    )
  );

  return {
    width:
      maxX -
      minX +
      edgePadding * 2,

    height:
      maxY -
      minY +
      edgePadding * 2,

    offsetX:
      edgePadding - minX,

    offsetY:
      edgePadding - minY,
  };
}