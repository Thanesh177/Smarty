const getPostTopics = (post) => {
  const rawValues = [
    post?.topic,
    post?.topics,
    post?.category,
    post?.categories,
    post?.roomName,
    post?.subject,
    post?.tags,
  ];

  return rawValues
    .flatMap((value) => {
      if (Array.isArray(value)) {
        return value;
      }

      if (
        typeof value === 'string' &&
        value.includes(',')
      ) {
        return value.split(',');
      }

      return [value];
    })
    .map(getTopicValue)
    .filter(Boolean);
};

