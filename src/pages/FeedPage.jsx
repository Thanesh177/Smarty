const areTopicsEquivalent = (left, right) => {
  const normalizedLeft = getCanonicalTopic(left);
  const normalizedRight = getCanonicalTopic(right);

  return Boolean(
    normalizedLeft &&
      normalizedRight &&
      normalizedLeft === normalizedRight
  );
};

